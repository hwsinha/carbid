create table users (
                       id            bigint generated by default as identity primary key,
                       name          varchar(255) not null,
                       email         varchar(255) not null,
                       password_hash varchar(255) not null,
                       role          varchar(255) not null,
                       city          varchar(255) not null,
                       created_at    timestamp(6) with time zone not null,
                       constraint uq_users_email unique (email),
                       constraint ck_users_role check (role in ('BUYER', 'DEALER', 'ADMIN'))
);

create table cars (
                      id                bigint generated by default as identity primary key,
                      brand             varchar(255) not null,
                      model             varchar(255) not null,
                      variant           varchar(255) not null,
                      ex_showroom_price numeric(12, 2) not null
);

create table dealers (
                         id            bigint generated by default as identity primary key,
                         showroom_name varchar(255) not null,
                         city          varchar(255) not null,
                         user_id       bigint not null,
                         constraint uq_dealers_user unique (user_id),
                         constraint fk_dealers_user foreign key (user_id) references users (id)
);

create table buy_groups (
                            id               bigint generated by default as identity primary key,
                            car_id           bigint not null,
                            city             varchar(255) not null,
                            min_members      integer not null,
                            status           varchar(255) not null,
                            deadline         timestamp(6) with time zone not null,
                            bidding_deadline timestamp(6) with time zone,
                            created_by_id    bigint not null,
                            created_at       timestamp(6) with time zone not null,
                            version          bigint,
                            winning_bid_id   bigint,
                            constraint uq_buy_groups_winning_bid unique (winning_bid_id),
                            constraint fk_buy_groups_car foreign key (car_id) references cars (id),
                            constraint fk_buy_groups_created_by foreign key (created_by_id) references users (id),
                            constraint ck_buy_groups_status check (status in ('OPEN', 'BIDDING', 'LOCKED', 'CLOSED', 'EXPIRED'))
);

create table group_members (
                               id        bigint generated by default as identity primary key,
                               group_id  bigint not null,
                               user_id   bigint not null,
                               joined_at timestamp(6) with time zone not null,
                               constraint uq_group_members_group_user unique (group_id, user_id),
                               constraint fk_group_members_group foreign key (group_id) references buy_groups (id),
                               constraint fk_group_members_user foreign key (user_id) references users (id)
);

create table bids (
                      id         bigint generated by default as identity primary key,
                      group_id   bigint not null,
                      dealer_id  bigint not null,
                      price      numeric(12, 2) not null,
                      notes      varchar(500),
                      created_at timestamp(6) with time zone not null,
                      constraint fk_bids_group foreign key (group_id) references buy_groups (id),
                      constraint fk_bids_dealer foreign key (dealer_id) references dealers (id)
);

alter table buy_groups
    add constraint fk_buy_groups_winning_bid foreign key (winning_bid_id) references bids (id);

create index idx_bids_group_dealer on bids (group_id, dealer_id);
create index idx_bids_group_price  on bids (group_id, price);
create index idx_group_members_user on group_members (user_id);
create index idx_buy_groups_status_deadline on buy_groups (status, deadline);